// protoc validates the contract; this generator reads its binary descriptors, not source regexes.
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const check = process.argv.includes('--check')
const output = (path, text) => {
  if (check) { if (readFileSync(path, 'utf8') !== text) throw Error('Generated schema is stale: ' + path) }
  else writeFileSync(path, text)
}
const tmp = mkdtempSync(resolve(tmpdir(), 'canopy-proto-'))
function fields(b) {
  let p = 0
  const out = {}
  function v() { let n = 0, shift = 0; do { const c = b[p++]; n += (c & 127) * 2 ** shift; if (!(c & 128)) return n; shift += 7 } while (p < b.length); throw Error('truncated descriptor') }
  while (p < b.length) {
    const tag = v(), wire = tag & 7, key = tag >>> 3
    let x
    if (wire === 0) x = v()
    else if (wire === 2) { const n = v(); x = b.subarray(p, p + n); p += n }
    else throw Error('unexpected descriptor wire')
    ;(out[key] ??= []).push(x)
  }
  return out
}
const str = (f, n) => f[n]?.[0]?.toString() ?? ''
try {
  execFileSync('protoc', ['-I', resolve(root, 'proto'), '--include_imports', '--descriptor_set_out=' + resolve(tmp, 'schema.pb'), 'canopy/api/v1/api.proto', 'grpc/health/v1/health.proto'])
  const files = fields(readFileSync(resolve(tmp, 'schema.pb')))[1].map(fields)
  const messages = {}, enums = {}, methods = {}, mapEntries = new Set()
  for (const file of files) {
  // Custom command options use descriptors at generation time only. They are
  // not transport messages, and their nested names are not globally unique.
  if (str(file, 1) === 'google/protobuf/descriptor.proto') continue
  const pkg = str(file, 2)
  for (const raw of file[5] ?? []) {
    const e = fields(raw); enums[str(e, 1)] = Object.fromEntries((e[2] ?? []).map(v => { const f = fields(v); return [str(f, 1), f[2][0]] }))
  }
  function addMessage(raw) {
    const m = fields(raw), name = str(m, 1)
    if (messages[name]) throw Error('Ambiguous protobuf short name: ' + name)
    if (m[7]?.[0] && fields(m[7][0])[7]?.[0] === 1) mapEntries.add(name)
    for (const nested of m[3] ?? []) addMessage(nested)
    for (const rawEnum of m[4] ?? []) {
      const e = fields(rawEnum); enums[str(e, 1)] = Object.fromEntries((e[2] ?? []).map(v => { const f = fields(v); return [str(f, 1), f[2][0]] }))
    }
    messages[name] = (m[2] ?? []).map(raw => {
      const f = fields(raw)
      return { name: str(f, 1), number: f[3][0], type: f[5][0], target: str(f, 6).split('.').pop(), repeated: f[4][0] === 3, optional: f[17]?.[0] === 1, oneof: f[9]?.[0] }
    })
  }
  for (const raw of file[4] ?? []) addMessage(raw)
  for (const raw of file[6] ?? []) {
    const s = fields(raw)
    for (const raw of s[2] ?? []) {
      const m = fields(raw), name = str(s, 1) + '/' + str(m, 1)
      methods[name] = { path: '/' + pkg + '.' + name, input: str(m, 2).split('.').pop(), output: str(m, 3).split('.').pop(), clientStream: !!m[5]?.[0], serverStream: !!m[6]?.[0] }
    }
  }
  }
  for (const fs of Object.values(messages)) for (const f of fs) if (f.repeated && mapEntries.has(f.target)) f.map = true
  const scalar = {1:'number',2:'number',3:'string',4:'string',5:'number',6:'string',7:'number',8:'boolean',9:'string',12:'Uint8Array',13:'number',15:'number',16:'string',17:'number',18:'string'}
  let ts = '// Contract SHA256: ' + createHash('sha256').update(readFileSync(resolve(root, 'proto/canopy/api/v1/api.proto'))).update(readFileSync(resolve(root, 'proto/grpc/health/v1/health.proto'))).digest('hex') + '\n'
  ts += '// GENERATED by scripts/generate-remote.mjs. Do not edit. uint64/int64 use decimal strings.\n'
  for (const [name, values] of Object.entries(enums)) ts += `export const ${name} = ${JSON.stringify(values)} as const\nexport type ${name} = number\n`
  for (const [name, fs] of Object.entries(messages)) {
    ts += `export interface ${name} {\n`
    for (const f of fs) ts += `  ${f.name}${f.optional || f.oneof !== undefined || (f.type === 11 && !f.repeated) ? '?' : ''}: ${f.map ? `Record<string, ${scalar[messages[f.target][1].type] ?? messages[f.target][1].target}>` : `${scalar[f.type] ?? f.target}${f.repeated ? '[]' : ''}`}\n`
    ts += '}\n'
  }
  ts += 'export interface RpcTypes {\n'
  for (const [name,m] of Object.entries(methods)) ts += `  '${name}': { input: ${m.input}; output: ${m.output} }\n`
  ts += '}\nexport const methods = ' + JSON.stringify(methods, null, 2) + ' as const\n'
  ts += 'export const messages = ' + JSON.stringify(messages) + ' as const\n'
  output(resolve(root, 'mobile/src/lib/remote/grpc/schema.ts'), ts)
  output(resolve(root, 'mobile/modules/canopy-remote/android/src/main/java/tech/itsol/canopy/remote/Methods.kt'), 'package tech.itsol.canopy.remote\ninternal val methods = mapOf(\n' + Object.entries(methods).map(([,m]) => `  "${m.path.slice(1)}" to "${m.clientStream ? 'BIDI_STREAMING' : m.serverStream ? 'SERVER_STREAMING' : 'UNARY'}"`).join(',\n') + '\n)\n')
  output(resolve(root, 'mobile/modules/canopy-remote/ios/Methods.json'), JSON.stringify(methods))
} finally { rmSync(tmp, { recursive: true, force: true }) }
